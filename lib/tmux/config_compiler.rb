# frozen_string_literal: true

module Tmux
  class ConfigCompiler
    INDENT = "  "

    class << self
      def quote(value, expand: true)
        return value.to_s if value.is_a?(Numeric)
        return "on" if value.equal?(true)
        return "off" if value.equal?(false)
        escaped = value.to_s.gsub("\\") { "\\\\" }.gsub('"') { '\\"' }
        escaped = escaped.gsub("$", "\\$").sub(/\A~/, "\\~") unless expand
        "\"#{escaped}\""
      end
    end

    def compile(nodes)
      lines(nodes).join("\n") + "\n"
    end

    private

    def lines(nodes)
      nodes.flat_map do |node|
        text = compile_node(node)
        text.empty? ? [""] : text.split("\n", -1)
      end
    end

    def compile_node(node)
      case node
      when ConfigNode::Blank then ""
      when ConfigNode::Command then node.text
      when ConfigNode::SetOption then compile_option(node)
      when ConfigNode::UnsetOption then compile_unset(node)
      when ConfigNode::IfShell then compile_if_shell(node)
      when ConfigNode::Condition then compile_condition(node)
      else raise Error, "unknown config node: #{node.inspect}"
      end
    end

    def scope_flags(scope) = {global: "-g", window: "-gw", server: "-s"}.fetch(scope)

    def compile_option(node)
      flags = scope_flags(node.scope)
      flags += "a" if node.append
      value = node.value.is_a?(Format) ? node.value.to_tmux : node.value
      "set-option #{flags} #{node.name} #{self.class.quote(value, expand: node.expand)}"
    end

    def compile_unset(node)
      "set-option #{scope_flags(node.scope)}u #{node.name}"
    end

    # if-shell with { } command blocks, one command per line.
    def compile_if_shell(node)
      parts = ["if-shell"]
      parts << "-b" if node.background
      parts << "-F" if node.format
      parts << self.class.quote(node.test)
      text = "#{parts.join(' ')} #{block(node.success)}"
      text += " #{block(node.failure)}" unless node.failure.empty?
      text
    end

    def block(nodes)
      body = lines(nodes).map { |line| line.empty? ? line : "#{INDENT}#{line}" }
      ["{", *body, "}"].join("\n")
    end

    # The condition is generated by tmux.rb and never contains a single quote;
    # single quotes keep tmux from treating its backslashes as escapes.
    def compile_condition(node)
      text = ["%if '#{node.condition}'", *lines(node.body)]
      text.concat(["%else", *lines(node.otherwise)]) unless node.otherwise.empty?
      text << "%endif"
      text.join("\n")
    end
  end
  private_constant :ConfigCompiler
end
